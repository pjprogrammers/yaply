/**
 * Flattens the curated categories and drops repeated spellings. A duplicate
 * would silently increase that word's odds, so the dedupe is part of the
 * selection contract rather than a one-off cleanup.
 */
function flattenUnique(groups: readonly (readonly string[])[]): string[] {
  const seen = new Set<string>();
  const words: string[] = [];
  for (const group of groups) {
    for (const word of group) {
      if (seen.has(word)) continue;
      seen.add(word);
      words.push(word);
    }
  }
  return words;
}

