/** Flattened bank used by the random pair selector. */
export const SPY_WORD_PAIRS: SpyWordPair[] = Object.entries(SPY_WORD_POOLS).flatMap(
  ([categoryId, seeds]) =>
    seeds.map(([wordA, wordB, difficulty], index) => ({
      id: `${categoryId}-${String(index + 1).padStart(3, "0")}`,
      categoryId,
      wordA,
      wordB,
      difficulty,
    })),
);

export const SPY_WORD_PAIR_BY_ID = new Map(SPY_WORD_PAIRS.map((pair) => [pair.id, pair]));
