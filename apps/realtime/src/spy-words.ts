import type { SpyDifficulty } from "@yaply/shared/types";

/**
 * Curated Who's the Spy word pairs. Every pair is deliberately authored rather
 * than generated: the civilian and spy words must be related enough for the spy
 * to bluff, yet different enough that a careful clue can expose them.
 *
 * Difficulty is stored on the pair instead of being inferred from string
 * similarity. `easy` pairs sit in the same broad family, `normal` pairs are
 * close siblings and `hard` pairs are easy to confuse even after several
 * clues.
 */
